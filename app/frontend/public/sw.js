// The service worker.
//
// It exists for one reason: the app is used in the field, at an airfield, on a
// phone with poor signal, and the shell should open without waiting for the
// network. It is NOT an offline-writes feature -- that is explicitly out of v1
// scope (app/APP.md section 2).
//
// THE RULE THAT MATTERS: this worker never caches a logbook response.
//
// Every /logbook/api/ response is personal data -- names, dates, locations, a
// movement history spanning 14 years -- and the server marks all of them
// `Cache-Control: no-store` precisely so no intermediary and no browser cache
// on a shared device keeps them. A service worker is a cache that ignores that
// header unless it is written not to, so storing an API response here would
// quietly undo a control the server states explicitly, and would leave the
// owner's logbook readable on the device after the session was revoked.
// The API is therefore passed straight through, untouched and unstored.
//
// Written by hand rather than generated by a build plugin: the whole policy is
// forty lines and it is the kind of policy that has to be read to be trusted
// (CLAUDE.md rule 0.3, keep the dependency tree near-empty).

// Bumped whenever the shell changes. The activate handler deletes every cache
// that is not this one, so an old bundle cannot outlive a deploy.
const CACHE = 'logbook-shell-v2'

const BASE = '/logbook/'
const SHELL = BASE

/**
 * policy decides what to do with a request. Pure and exported onto the global
 * so it can be tested against this exact file rather than against a copy.
 *
 *   'passthrough' -- go to the network, store nothing. Everything under the
 *                    API, and anything that is not a GET.
 *   'shell'       -- a navigation. Network first, fall back to the cached
 *                    shell so the app opens with no signal.
 *   'asset'       -- a content-hashed build asset. Cache first: the filename
 *                    changes when the content does, so a hit is never stale.
 *   'bypass'      -- not ours; let the browser do what it would have done.
 */
function policy(request, url) {
  if (url.origin !== self.location.origin) return 'bypass'
  // Never cache the logbook itself. Checked before anything else so no later
  // rule can accidentally catch an API URL.
  if (url.pathname.startsWith(BASE + 'api/')) return 'passthrough'
  if (request.method !== 'GET') return 'passthrough'
  if (request.mode === 'navigate') return 'shell'
  // index.html is the one file under /logbook/ that is NOT content-hashed:
  // its name stays the same while its contents change on every deploy. Treating
  // it as an immutable asset is how a phone keeps opening last week's build.
  if (url.pathname === SHELL || url.pathname === BASE + 'index.html') return 'shell'
  if (url.pathname.startsWith(BASE + 'assets/')) return 'asset'
  if (url.pathname.startsWith(BASE)) return 'asset'
  return 'bypass'
}
self.policy = policy

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.add(SHELL)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url)
  const what = policy(event.request, url)

  // Not responding at all leaves the request entirely to the browser, which is
  // what the API must get: no interception, no copy, no storage.
  if (what === 'passthrough' || what === 'bypass') return

  if (what === 'shell') {
    event.respondWith(
      // `cache: 'no-store'` goes past the browser's own HTTP cache. Without it
      // "network first" is only as fresh as whatever that cache is holding,
      // and a phone with index.html cached keeps opening the previous build
      // with the worker none the wiser. The document is a few hundred bytes;
      // the hashed bundles it points at are still cached hard.
      fetch(event.request, { cache: 'no-store' })
        .then((res) => {
          // Keep the latest shell for the next cold start with no signal.
          const copy = res.clone()
          caches.open(CACHE).then((c) => c.put(SHELL, copy))
          return res
        })
        .catch(() => caches.match(SHELL).then((hit) => hit || Response.error())),
    )
    return
  }

  // 'asset': cache first. Build assets are content-hashed, so a cache hit is
  // by definition the right bytes for that filename.
  event.respondWith(
    caches.match(event.request).then(
      (hit) =>
        hit ||
        fetch(event.request).then((res) => {
          if (res.ok && res.status === 200) {
            const copy = res.clone()
            caches.open(CACHE).then((c) => c.put(event.request, copy))
          }
          return res
        }),
    ),
  )
})
